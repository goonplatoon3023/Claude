function pf(overrides: Partial<PhrasingFeatures> = {}): PhrasingFeatures {
  return {
    hasNegation: false,
    hasDoubleNegation: false,
    hasAbsoluteLanguage: false,
    hasQualifiedLanguage: false,
    sentenceComplexity: 'simple',
    vocabularyLevel: 'basic',
    keyTerms: [],
    ...overrides,
  };
}

